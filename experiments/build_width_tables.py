#!/usr/bin/env python3
"""Per-family LaTeX tables for the 600s width study.

Writes docs/paper/tables/w_<key>.tex, one self-contained table per family, with
rows = physics sweep points and columns = complex sinh at width 128 and 64 plus
the real baselines (all width 128).  Best entry per row in bold.  These are
\\input by the per-problem subsections of osc_experiments.tex.
"""
from __future__ import annotations

from pathlib import Path

import plot_width as pw

OUTDIR = pw.pc.ROOT / "docs" / "paper" / "tables"
OUTDIR.mkdir(parents=True, exist_ok=True)

HEAD = {
    "complex_sinh_128": r"complex $\sinh_{128}$",
    "complex_sinh_64":  r"complex $\sinh_{64}$",
    "fourier": "Fourier", "siren": "SIREN", "mscale": "MscaleDNN",
    "tanh": r"split $\tanh$",
}
REAL_COLS = ["complex_sinh_128", "complex_sinh_64", "fourier", "siren", "mscale"]
CPLX_COLS = ["complex_sinh_128", "complex_sinh_64", "siren", "fourier", "tanh"]
SYM = {"poly1d": "m", "poly2d": "m", "helmholtz": "a", "helmvc": "a", "chirp": "a",
       "plate": "m", "beam": "m", "platemix": "m", "kdv": "k", "cahn": "a",
       "nls": "k", "maxwell": "a"}
NICE = {"poly1d": "Polyharmonic (1D)", "poly2d": "Polyharmonic (2D)",
        "helmholtz": "High-wavenumber Helmholtz",
        "helmvc": "Variable-coefficient Helmholtz", "chirp": "Radial chirp",
        "plate": "Kirchhoff plate", "beam": "Euler--Bernoulli beam",
        "platemix": "Mixed-mode plate", "kdv": "Linearized KdV",
        "cahn": "Cahn--Hilliard (6th order)", "nls": "Cubic NLS",
        "maxwell": "Time-harmonic Maxwell"}


def fmt(x):
    return f"{x:.2e}".replace("e-0", "e-").replace("e+0", "e")


def build(fam):
    means, _ = pw.load(fam)
    if not means:
        return False
    key = fam["key"]
    cols = [c for c in (CPLX_COLS if key in ("nls", "maxwell") else REAL_COLS)
            if c in means]
    sweeps = sorted({s for c in cols for s, _ in means[c]})
    lut = {c: dict(means[c]) for c in cols}
    sym = SYM.get(key, "a")

    lines = [f"% auto-generated by experiments/build_width_tables.py",
             r"\begin{table}[htbp]", r"\centering", r"\small",
             rf"\caption{{{NICE.get(key, key)}: relative $L^2$ error at 600\,s "
             r"(2 seeds). Real baselines at width 128; the complex $\sinh$ net at "
             r"width 128 and 64 ($\sim$2$\times$ and $\sim$half the baselines' "
             r"equivalent DOF). Best per row in bold.}",
             rf"\label{{tab:w-{key}}}",
             r"\begin{tabular}{@{}l" + "r" * len(cols) + r"@{}}", r"\toprule",
             f"${sym}$ & " + " & ".join(HEAD[c] for c in cols) + r" \\",
             r"\midrule"]
    for s in sweeps:
        vals = {c: lut[c].get(s) for c in cols}
        best = min((v for v in vals.values() if v is not None), default=None)
        cells = []
        for c in cols:
            v = vals[c]
            if v is None:
                cells.append("--")
            elif best is not None and abs(v - best) < 1e-12:
                cells.append(rf"\textbf{{{fmt(v)}}}")
            else:
                cells.append(fmt(v))
        sval = f"{s:g}"
        lines.append(f"{sval} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    (OUTDIR / f"w_{key}.tex").write_text("\n".join(lines))
    print(f"[ok] wrote {OUTDIR / f'w_{key}.tex'}  ({len(sweeps)} rows, {len(cols)} cols)")
    return True


def main():
    n = sum(build(fam) for fam in pw.FAMILIES)
    print(f"\n[done] {n} tables -> {OUTDIR}")


if __name__ == "__main__":
    main()
